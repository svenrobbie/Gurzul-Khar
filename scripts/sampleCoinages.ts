// Prints a review sheet of coined words for the ear test that ROADMAP.md
// phase 1 gates on: read these aloud next to khar, dor, ghûldor and nâzgam.
// If they stand out as machine-made, tune the weights and the euphony rules
// and regenerate — but only BEFORE coiner_v1 is frozen.
//
//   npx tsx scripts/sampleCoinages.ts > COINER_SAMPLE.md
import { coin } from "../engine/lexicon/coiner.js";
import { lexicon } from "../engine/data.js";
import { GROUPS, POS_OF } from "./commonWords.js";


console.log("# coiner_v1 — sample for the ear test\n");
console.log(`Generated by \`scripts/sampleCoinages.ts\` from the frozen weight tables in \`data/phonology/coinerWeights_v1.json\`, measured over ${lexicon.entries.length} hand-authored entries.\n`);
console.log("Read each column aloud. The test is not whether a word is legal — the validator already guarantees that — but whether it would look out of place next to **khar**, **dor**, **ghûldor**, **nâzgam** and **rûkakûk** in the dictionary.\n");

const taken = new Set(lexicon.entries.map((e) => e.gkh.replace(/-/g, "").toLowerCase()));
for (const [group, words] of Object.entries(GROUPS)) {
  const pos = POS_OF[group] ?? "noun";
  console.log(`## ${group}\n`);
  const rows = words.map((w) => {
    const r = coin({ lemma: w, pos, lang: "nl" }, { taken });
    taken.add(r.gkh);
    return `| ${w} | **${r.gkh}** | ${r.ipa} |`;
  });
  console.log("| Dutch | Gurzûl Khar | IPA |");
  console.log("| --- | --- | --- |");
  console.log(rows.join("\n"));
  console.log("");
}
