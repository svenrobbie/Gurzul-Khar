// Prints a review sheet of coined words for the ear test that ROADMAP.md
// phase 1 gates on: read these aloud next to khar, dor, ghûldor and nâzgam.
// If they stand out as machine-made, tune the weights and the euphony rules
// and regenerate — but coiner_v1 is frozen, so that means a coiner_v2.
//
//   npm run coiner:sample
import { engine, readData } from "./lib/engine.mjs";
import { GROUPS, POS_OF } from "./commonWords.mjs";

const gkh = await engine();
const lexicon = await readData("data/lexicon/lexicon.json");

console.log("# coiner_v1 — sample for the ear test\n");
console.log(
  `Generated by \`scripts/sampleCoinages.mjs\` from the frozen weight tables in \`data/phonology/coinerWeights_v1.json\`, measured over ${lexicon.entries.length} hand-authored entries.\n`,
);
console.log(
  "Read each column aloud. The test is not whether a word is legal — the validator already guarantees that — but whether it would look out of place next to **khar**, **dor**, **ghûldor**, **nâzgam** and **rûkakûk** in the dictionary.\n",
);

// One batch across every group, so a word is never issued twice — the same
// reserved set the translator would have built up coining them in this order.
const requests = [];
for (const [group, words] of Object.entries(GROUPS)) {
  for (const word of words) requests.push({ group, word, pos: POS_OF[group] ?? "noun" });
}
const results = gkh
  .coin_batch(requests.map((r) => `${r.word}\t${r.pos}\tnl`).join("\n"))
  .split("\n")
  .filter(Boolean)
  .map((line) => line.split("\t")[3]);

let i = 0;
for (const [group, words] of Object.entries(GROUPS)) {
  console.log(`## ${group}\n`);
  console.log("| Dutch | Gurzûl Khar | IPA |");
  console.log("| --- | --- | --- |");
  for (const word of words) {
    const form = results[i++];
    console.log(`| ${word} | **${form}** | ${gkh.word_ipa(form)} |`);
  }
  console.log("");
}
